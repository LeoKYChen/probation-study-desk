assert.match(app,/StarestoVocabulary/);assert.match(app,/words\.plan/);assert.match(app,/words\.rate/);
assert.doesNotMatch(app,/localStorage\.(?:clear|removeItem)/,'do not erase old data');
const state=core.createState();assert.deepEqual(Object.keys(state.wordProgress),[]);
const today='2026-10-17',day1=vocab.plan(state,today);

assert.equal(bad.streak,1);assert.equal(bad.due,'2026-10-18');
assert.throws(()=>vocab.rate(state,today,day1.new[0],true),/已評分/);
const next=vocab.plan(state,'2026-10-18');
assert.ok(next.review.includes(day1.new[0]),'review due tomorrow');
assert.equal(next.new[0],day1.new[1],'not-rated words carry forward and are not silently lost');
const rated2=vocab.rate(state,'2026-10-18',day1.new[0],true);
assert.equal(rated2.due,'2026-10-21','second known review after three days');
vocab.plan(state,'2026-10-19');vocab.plan(state,'2026-10-20');
assert.ok(!state.wordDays['2026-10-20'].review.includes(day1.new[0]));
const due3=vocab.plan(state,'2026-10-21');
assert.ok(due3.review.includes(day1.new[0]));
const retry=vocab.rate(state,'2026-10-21',day1.new[0],false);
assert.equal(retry.streak,0);assert.equal(retry.due,'2026-10-22','forgotten word returns next day');
assert.ok(vocab.plan(state,'2026-10-22').review.includes(day1.new[0]));
const customState=core.createState(),initial=vocab.plan(customState,today);

'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const dir=__dirname;
function readModule(name){const sandbox={module:{exports:{}},Intl,Date,Number,String,Object,Set,Array,JSON,Math,RegExp};vm.runInNewContext(fs.readFileSync(path.join(dir,name),'utf8'),sandbox,{filename:name});return sandbox.module.exports}

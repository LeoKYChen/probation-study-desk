assert.throws(()=>vocab.addCustomWord(customState,'resilience','韌性'),/已存在/);
assert.throws(()=>vocab.addCustomWord(customState,'<script>','注入'),/請輸入/);
assert.throws(()=>vocab.addCustomWord(customState,'evidence','證據'),/已存在/);
assert.ok(vocab.plan(customState,'2026-10-18').new.includes('mine-resilience'),'custom terms prioritized on next day');
assert.deepEqual(initial.new,customState.wordDays[today].new,'do not rewrite frozen day after adding word');
const full=core.createState(),assigned=new Set();
for(let i=0;i<34;i++){
 const d=new Date(Date.UTC(2026,9,17+i)).toISOString().slice(0,10);
 const plan=vocab.plan(full,d);
 for(const id of plan.new){
   assert.ok(!assigned.has(id),'no new repeats after learning: '+id);
   assigned.add(id);
   vocab.rate(full,d,id,true);
 }
}
assert.equal(assigned.size,180,'all 180 cards assigned at most once');
assert.equal(vocab.plan(full,'2026-11-25').new.length,0,'no invented words after catalog exhaustion');
assert.equal(vocab.stats(full,'2026-11-25').known,180);

for(const id of uiIds)assert.ok(ids.includes(id)||id==="rename","missing UI ID "+id);
assert.ok(!src.includes('localStorage.getItem("probationStudyIsland.v1")'),"v3 should never be read implicitly");
assert.ok(src.includes('indexedDB.open("probation-study-island-v4"'),"use separate v4 database");
assert.ok(src.includes('if(s.collected.includes(spot.id))return false;'),"collection must be idempotent");
assert.ok(src.includes('if(s.questClaims.includes(id))return false;'),"quest rewards must be idempotent");
assert.ok(src.includes('if(today[id])return false;'),"daily learning rewards must be idempotent");
assert.ok(src.includes('if(s.focusRewards.includes(token))return false;'),"focus rewards must be idempotent");
const canvas={getContext(){return {}},addEventListener(){}};
const dom={addEventListener(){},getContext(){return {}},classList:{add(){}},style:{},dataset:{},setAttribute(){},textContent:"",innerHTML:""};
const document={getElementById(id){return id==="world"?canvas:dom},querySelectorAll(){return []},addEventListener(){}};
const context={document,window:{addEventListener(){}},indexedDB:{},Date,Math,performance:{now(){return 0}},setInterval(){},setTimeout(){},clearTimeout(){},console};
const inject="\nglobalThis.__unit={defaultSave,dayUpdate,isStaticBlocked,walkable,routeTo,validSave,RESOURCE_SPOTS,TREES,POND,NPCS,get player(){return player},setState(s){state=s}};\n})();";
const instrumented=src.replace(/\ninitialize\(\);\n\}\)\(\);\s*$/,inject);
assert.ok(instrumented.includes("globalThis.__unit"),"test injection not applied");
vm.runInNewContext(instrumented,context,{filename:"game.js"});
const g=context.__unit;
assert.equal(g.RESOURCE_SPOTS.length,12);
assert.equal(g.NPCS.length,4);
assert.equal(g.isStaticBlocked(8,3),true,"house must be blocked");
assert.equal(g.walkable(6,8),false,"resident must block walking");
assert.equal(g.walkable(9,9),true,"spawn must be walkable");

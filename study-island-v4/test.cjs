const shell=g.routeTo(2,12,false);assert.ok(Array.isArray(shell)&&shell.length>0,"must reach beach");
for(const [x,y] of shell)assert.equal(g.walkable(x,y),true,"route crosses obstacle");
const fox=g.routeTo(6,8,true);assert.ok(fox&&fox.length>0);
const last=fox.at(-1);assert.equal(Math.abs(last[0]-6)+Math.abs(last[1]-8),1,"conversation ends beside resident");
const save=g.defaultSave();assert.equal(g.validSave(save),true,"new save must validate");
save.collected=["shell-1"];save.spawnDate="2025-01-01";save.bag.shell=2;g.dayUpdate(save);
assert.equal(save.collected.length,0,"new day refreshes collection points");
assert.equal(save.bag.shell,2,"new day must never clear acquired inventory");
const corrupt=g.defaultSave();corrupt.player={x:9,y:3};assert.equal(g.validSave(corrupt),false,"invalid spawn must not import");

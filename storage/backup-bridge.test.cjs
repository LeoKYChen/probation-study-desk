'use strict';
const assert=require('node:assert/strict');
const {indexedDB}=require('fake-indexeddb');
(async()=>{
 await import('./indexeddb.js');
 await import('./backup-bridge.js');
 await import('../backup/unified-core.js');
 const core=globalThis.PSDUnifiedBackup, store=await globalThis.PSDLearningStorage.open(indexedDB);
 const bridge=globalThis.PSDIndexedBackup.create(core,store,'https://example.test');
 const key='probation-study-desk-v24', a=JSON.stringify({Q1:{issue:'答案甲'}}), b=JSON.stringify({Q1:{issue:'答案乙'},Q2:{issue:'另一題'}});
 await store.compareAndSet(key,null,a);
 const exported=await bridge.collect();
 assert.equal(exported.data[key],a); core.validate(exported);
 const incoming={...exported,data:{[key]:b}};
 let plan=await bridge.plan(incoming);
 assert.ok(plan.conflicts.length);
 await bridge.apply(plan);
 let data=await bridge.snapshot();
 assert.equal(JSON.parse(data[key]).Q1.issue,'答案甲');
 assert.equal(JSON.parse(data[key]).Q2.issue,'另一題');
 assert.ok(JSON.parse(data[core.CONFLICT_KEY]).entries.length);
 plan=await bridge.plan(incoming);
 const changed=JSON.stringify({Q1:{issue:'分頁新增'}});
 await store.compareAndSet(key,data[key],changed);
 await assert.rejects(bridge.apply(plan),/其他分頁/);
 data=await bridge.snapshot(); assert.equal(data[key],changed);
 assert.ok(JSON.parse(data[core.CONFLICT_KEY]).entries.length);
 await assert.rejects(bridge.apply({baseline:data,changes:{'unknown':'{}'}}),/不支援/);
 store.close();
 console.log('PASS IndexedDB backup export, safe merge, conflict archive and stale preview rejection');
})().catch(e=>{console.error(e);process.exitCode=1;});

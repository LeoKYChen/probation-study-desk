'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
(async()=>{
 const moduleText=read('study-desk/weakness.js');
 const mod=await import('data:text/javascript;base64,'+Buffer.from(moduleText).toString('base64'));
 assert.equal(mod.WEAKNESS_CATEGORIES.length,7);
 assert.equal(mod.validateWeaknessCategory('norm'),'norm');
 assert.throws(()=>mod.validateWeaknessCategory('invented'),/弱點類別/);
 const task={id:'attempt/1',subject:'心理學',question:{title:'心理測驗',topicKey:'心理學｜心理測驗'},due:'2026-10-25',
   feedback:[{id:'ai1',unverified:true,text:'AI 猜測存在問題'}],
   corrections:[{id:'c1',category:'norm',gap:'混淆信度與效度',text:'信度是測量一致性',at:'2026-10-22T12:00:00Z'}],recalls:[]};
 let items=mod.confirmedWeaknesses([task]);
 assert.equal(items.length,1,'only human-confirmed corrections count');
 assert.equal(items[0].category,'norm');
 assert.equal(mod.weaknessStats(items).total,1);
 assert.equal(mod.weaknessStats(items).subjects[0].subject,'心理學');
 assert.equal(mod.confirmedWeaknesses([{...task,corrections:[]}]).length,0,'AI-only feedback never counts');
 assert.equal(mod.confirmedWeaknesses([{...task,corrections:[{id:'bad',gap:'',text:'訂正'}]}]).length,0,'empty gaps do not count');
 items=mod.confirmedWeaknesses([{...task,corrections:[{id:'old',gap:'歷史缺口',text:'歷史訂正',at:'2025-01-01'}]}]);
 assert.equal(items[0].category,'other','old backups without categories remain readable');
 const second={...task,id:'attempt/2',question:{id:'q2',title:'第二道心理學題',topicKey:'心理學｜測驗'},corrections:[{id:'c2',category:'norm',gap:'另一題也混淆理論',text:'已訂正',at:'2026-10-23'}]};
 const first={...task,question:{...task.question,id:'q1'}};
 const trends=mod.weaknessTrends([first,second]);
 assert.equal(trends[0].recurring,true,'two distinct questions with confirmed same-category gaps are recurring');
 assert.equal(trends[0].distinctQuestions,2);
 assert.equal(trends[0].correctedAttempts,2);
 assert.equal(mod.weaknessTrends([first,{...first,id:'attempt/3'}])[0].recurring,false,'repeating the same question is not cross-question recurrence');
 assert.equal(mod.weaknessTrends([{...first,corrections:[first.corrections[0],{...first.corrections[0],id:'c1b'}]}])[0].correctedAttempts,1,'multiple correction paragraphs in one attempt count once');
 assert.equal(mod.weaknessTrends([{...first,corrections:[],feedback:[{text:'AI said wrong'}]}]).length,0);
 assert.equal(mod.recallTrajectory(first).status,'no-recall');
 const recallBase={...first,recalls:[{id:'r1',at:'2026-10-24',rating:'again'},{id:'r2',at:'2026-10-25',rating:'independent'}]};
 assert.equal(mod.recallTrajectory(recallBase).status,'improving');
 assert.equal(mod.recallTrajectory({...recallBase,recalls:[...recallBase.recalls,{id:'r3',at:'2026-10-26',rating:'again'}]}).status,'stable');
 assert.equal(mod.recallTrajectory({...recallBase,recalls:[{id:'r1',at:'2026-10-24',rating:'independent'},{id:'r2',at:'2026-10-25',rating:'again'}]}).status,'declining');
 assert.equal(mod.recallTrajectory({...first,recalls:[{id:'r0',at:'2026-10-20',rating:'independent'}]}).status,'no-recall','do not attribute pre-correction recall to post-correction learning');
 const app=read('study-desk/app.js'),html=read('study-desk/index.html'),sw=read('study-desk/sw.js');
 assert.match(html,/id="gap-category"/);assert.match(html,/id="track-weak-topic"/);assert.match(html,/id="weakness-board"/);
 assert.match(app,/confirmedBy:'user'/);assert.match(app,/if\(flag&&topicKey/);
 assert.match(app,/renderWeaknessBoard\(state\)/);
 assert.match(html,/id="weakness-trends"/);assert.match(html,/id="recall-trends"/);assert.match(app,/weaknessTrends\(attempts\(state\)\)/);
 assert.match(sw,/weakness\.js/);
 console.log('PASS: manual-only weakness categories, legacy compatibility, summary and offline shell');
})().catch(e=>{console.error(e);process.exitCode=1});

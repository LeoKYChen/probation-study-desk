/* v2.5.4 daily practice regression checks, no external dependencies. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=path=>fs.readFileSync(path,'utf8');
const root={};
function evaluate(path){vm.runInNewContext(read(path),{window:root,globalThis:root}, {filename:path,timeout:5000});}
evaluate('daily-simulation/model.js');
evaluate('v2.5/backup-core.js');
evaluate('v2.5/ai-simple-review-v254.js');
const M=root.PracticeModel,B=root.Backup25,A=root.AISimpleReview254;
assert.ok(M&&B&&A);
const d=M.dataset(JSON.parse(read('daily-simulation/questions.json')));
assert.equal(d.questions.length,d.count);
assert.ok(d.questions.length>0);
const sample=d.questions[0];
const old={answer:'初稿',review:false,updatedAt:'2026-10-17T00:00:00.000Z',questionSnapshot:M.signature(sample)};
const newer={...old,answer:'訂正答案',aiFeedback:'AI 批改示例'};
assert.equal(M.records({old}).old.answer,'初稿');
assert.equal(M.records({[sample.id]:newer})[sample.id].aiFeedback,'AI 批改示例');
const dailyFile={format:'probation-daily-github-records',schemaVersion:1,records:{[sample.id]:newer}};
assert.equal(M.backup(dailyFile)[sample.id].aiFeedback,'AI 批改示例');
const full=B.create({},{[sample.id]:newer});
assert.equal(B.validate(full).daily[sample.id].aiFeedback,'AI 批改示例');
const merged=B.merge(B.create({},{[sample.id]:old}),full);
assert.ok(merged.data.daily[sample.id]);
assert.deepEqual(Object.keys(merged.data.study),[],'每日題不得寫入考古題');
const script=read('v2.5/daily-practice.js');
const html=read('v2.5/daily-practice.html');
new vm.Script(script,{filename:'v2.5/daily-practice.js'});
const ids=[...script.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1]);
for(const id of new Set(ids))assert.ok(html.includes('id="'+id+'"'),'missing UI node '+id);
const matchStart=script.indexOf('function simulationQuestion(q){');
const matchEnd=script.indexOf('async function copyAI(){',matchStart);
assert.ok(matchStart>=0&&matchEnd>matchStart);
const functions=vm.runInNewContext('(()=>{'+script.slice(matchStart,matchEnd)+'; return {simulationQuestion,promptFor};})()', {M});
const {simulationQuestion,promptFor}=functions;
const law={...sample,id:'law',date:'2026-10-17',subject:'少年事件處理法',
 question:'分析少年事件處理法、刑法及刑事訴訟法的法律爭點。'};
const mixed={...sample,id:'mixed',subject:'少年事件處理法',
 question:'（一）依法分析保護處分（15分）。（二）運用心理學理論提出處遇（10分）。'};
assert.throws(()=>promptFor(law,''),/請先完成/);
const lawText=promptFor(law,'法律爭點分析答案');
assert.ok(lawText.includes(law.question)&&lawText.includes('法律爭點分析答案'));
assert.ok(lawText.includes('整題統一評分')&&lawText.includes('不按法律科目拆分分數'));
assert.ok(lawText.includes('【本次每日模擬題】')&&!lawText.includes('【原題】'));
assert.ok(!lawText.includes('年度／科目：116年'),'no fabricated exam year');
assert.ok(lawText.includes('\n\n'),'prompt uses actual newlines');
const mixedText=promptFor(mixed,'學理與法律分析答案');
assert.ok(mixedText.includes('須按題目設問分別評分'));
assert.ok(mixedText.includes('15分')&&mixedText.includes('10分'));
assert.ok(!mixedText.includes('【參考考點（未獨立審定）】'),'not include unreviewed reference materials');
const adapted=d.questions.find(q=>q.question.includes('- 原題：')&&q.question.includes('- 改編題'));
assert.ok(adapted,'test needs a source-versus-adapted question');
const adaptedPrompt=simulationQuestion(adapted);
assert.ok(adaptedPrompt.length>40);
assert.ok(!adaptedPrompt.includes('- 原題：'),'must not grade original exam statement');
assert.ok(!adaptedPrompt.includes('- 改編來源'),'must not grade editorial metadata');
assert.ok(promptFor(adapted,'模擬答案').includes(adaptedPrompt));
const edited=d.questions.find(q=>q.question.startsWith('將其深化為')&&q.question.includes('改編後實例申論題題目'));
assert.ok(edited);
assert.ok(simulationQuestion(edited).startsWith('案例事實：'));
assert.ok(!promptFor(edited,'案例作答').includes('四欄標準表格理論與個案處遇深度結合：'),'do not include editor preface');
const manifest=JSON.parse(read('offline-manifest.json')),assets=manifest.assets.map(x=>x.url);
for(const path of ['v2.5/daily-practice.html','v2.5/daily-practice.css','v2.5/daily-practice.js'])
 assert.ok(assets.includes(path),'missing PWA asset '+path);
assert.equal(assets.length,new Set(assets).size,'duplicate PWA assets');
assert.ok(read('v2.5/index.html').includes('href="daily-practice.html"'));
assert.ok(html.includes('href="../daily-simulation/"'),'舊每日題瀏覽連結必須保留');
const draftIds=['draftIssue','draftBasis','draftAnalysis','draftConclusion','exportEssay'];
for(const id of draftIds)assert.ok(html.includes('id="'+id+'"'),'missing essay workbench node '+id);
assert.ok(html.includes('>我的練習紀錄</h3>'));
assert.ok(script.includes('essayDrafts:readDrafts()'),'four essays should share daily records');
assert.ok(script.includes('saved:currentSaved()'),'complete backup includes bookmarks');
assert.ok(script.includes('timers:validateTimers(timers)'),'complete backup includes timers');
assert.ok(script.includes('mergedRecord(next[id],record)'),'import preserves fields that old backups omit');
const older={...newer,essayDrafts:{issues:'爭點',basis:'規範',analysis:'涵攝',conclusion:'結論'}};
assert.equal(M.backup({format:'probation-daily-github-records',schemaVersion:1,records:{[sample.id]:older}})[sample.id].essayDrafts.conclusion,'結論');
assert.equal(B.validate(B.create({},{[sample.id]:older})).daily[sample.id].essayDrafts.basis,'規範');

assert.ok(script.includes("const KEY='probation-daily-github:records:v1'"),'必須共用原每日題儲存鍵');
assert.ok(script.includes('persist({});records={};timers={};writeTimers()'),'只清每日題並重設計時');
// The evening room embeds the full four-grid + AI + MD workspace, not a redirect.
const browserHtml=read('daily-simulation/index.html');
const browserScript=read('daily-simulation/app.js');
new vm.Script(browserScript,{filename:'daily-simulation/app.js'});
for(const id of ['draftIssue','draftBasis','draftAnalysis','draftConclusion','answer','copyAI','aiFeedback','exportEssay','timer','startTimer','resetTimer'])
 assert.ok(browserHtml.includes('id="'+id+'"'),'missing inline field '+id);
assert.ok(!browserHtml.includes('id="practiceLink"'),'no redirect-only flow');
assert.ok(browserScript.includes("const KEY='probation-daily-github:records:v1'"),'inline editor shares the stable daily record key');
assert.ok(browserScript.includes("const TIMER_KEY='probation-daily-30min:session:v1'"),'same timer session key');
assert.ok(browserScript.includes('essayDrafts:readDrafts()'),'daily modal persists four drafts');
assert.ok(browserScript.includes('aiFeedback:$(\'aiFeedback\').value'),'daily modal persists AI comments');
assert.ok(browserScript.includes('text/markdown;charset=utf-8'),'daily modal exports UTF-8 markdown');
assert.ok(browserScript.includes('const ENABLE_NEWS_READING=false;'),'news reading must stay disabled');
const inlineStart=browserScript.indexOf('function simulationQuestion(q){');
const inlineEnd=browserScript.indexOf('async function copyAI(){',inlineStart);
assert.ok(inlineStart>=0&&inlineEnd>inlineStart,'daily browser must include grading prompt');
const inlineFns=vm.runInNewContext('(()=>{'+browserScript.slice(inlineStart,inlineEnd)+'; return {simulationQuestion,promptFor};})()',{M});
assert.equal(inlineFns.promptFor(law,'法律爭點分析答案'),promptFor(law,'法律爭點分析答案'),'both pages must use identical law rubric');
assert.equal(inlineFns.promptFor(mixed,'學理與法律分析答案'),promptFor(mixed,'學理與法律分析答案'),'both pages must use identical cross-subject rubric');
assert.equal(inlineFns.simulationQuestion(adapted),simulationQuestion(adapted),'both pages must display the same adapted essay prompt');

console.log('Daily v2.5.4 regression checks passed ('+d.count+' questions).');

assert.doesNotMatch(app,/localStorage\.(?:removeItem|clear)\s*\(/,'do not delete browser data');
assert.doesNotMatch(app,/psd-staresto-daily-v04|psd-common-subjects-v1/,'do not touch legacy keys in app code');
